import ExcelJS from 'exceljs'

import { buildTableExportWorkbook } from '../shared/export/table-export-xlsx'
import type { DealerProductionRowDto } from './dto/production-kpi.dto'
import { productionGoalExportLabels } from './production-goal-export-labels'
import {
  buildProductionGoalReportInfo,
  productionGoalColumns,
  productionGoalDatesValue,
  sortLikeProductionGrid,
} from './production-goal-export'

/** plans/plan-report-info-exports-tablas §4.1 / §5.1 (R1 and R2 of its review). */
describe('Production vs Goal export', () => {
  const rows: DealerProductionRowDto[] = [
    { dealerId: 1, dealer: 'Toyota Miami', wos: 10, value: 1000.5, goal: 2000, attainmentPct: 50 },
    { dealerId: 2, dealer: 'Lamborghini', wos: 3, value: 114996.53, goal: 0, attainmentPct: 0 },
    { dealerId: 3, dealer: 'Lexus PB', wos: 20, value: 3000, goal: 2500, attainmentPct: 120 },
  ]
  const generatedAt = new Date('2026-10-27T19:15:00Z')

  it('dates like the subtitle of the screen', () => {
    expect(productionGoalDatesValue('2026-10-01', '2026-10-27')).toBe('10/01/2026 – 10/27/2026')
    expect(productionGoalDatesValue('2026-10-27', '2026-10-27')).toBe('10/27/2026')
  })

  it('Report Info: every filter; removed dealers only when on, with the ones that have rows', () => {
    const labels = productionGoalExportLabels('en')
    const base = {
      labels,
      generatedAt,
      generatedBy: 'Ignacio',
      fechaDesde: '2026-10-01',
      fechaHasta: '2026-10-27',
      dealerNames: ['Toyota Miami', 'Lexus PB'],
      filterDateDone: true,
    }
    const off = buildProductionGoalReportInfo({ ...base, includeRemovedDealers: false, removedDealersWithRows: [] })
    expect(off.map((r) => r.field)).toEqual([
      'Report',
      'Generated',
      'Generated by',
      'Screen',
      'Dates',
      'Dealers',
      'Filter by completion date',
    ])
    expect(off[0].value).toBe('Production vs Goal by Dealer')
    expect(off[1].value).toBe('10/27/2026 3:15 PM ET')
    expect(off[3].value).toBe('Reports › Production vs Goal by Dealer')
    expect(off[5].value).toBe('Toyota Miami, Lexus PB')
    expect(off[6].value).toBe('Yes')

    const on = buildProductionGoalReportInfo({
      ...base,
      includeRemovedDealers: true,
      removedDealersWithRows: ['Lamborghini'],
    })
    expect(on.at(-1)).toEqual({ field: 'Include removed dealers', value: 'Yes — Lamborghini' })
    const onNone = buildProductionGoalReportInfo({ ...base, includeRemovedDealers: true, removedDealersWithRows: [] })
    expect(onNone.at(-1)).toEqual({ field: 'Include removed dealers', value: 'Yes' })
  })

  it('Spanish texts', () => {
    const info = buildProductionGoalReportInfo({
      labels: productionGoalExportLabels('es'),
      generatedAt,
      generatedBy: 'Ignacio',
      fechaDesde: '2026-10-01',
      fechaHasta: '2026-10-27',
      dealerNames: ['Toyota Miami'],
      filterDateDone: false,
      includeRemovedDealers: true,
      removedDealersWithRows: ['Lamborghini'],
    })
    expect(info.map((r) => r.field)).toEqual([
      'Reporte',
      'Generado',
      'Generado por',
      'Pantalla',
      'Fechas',
      'Sucursales',
      'Filtrar por fecha de terminación',
      'Incluir dealers eliminados',
    ])
    expect(info[6].value).toBe('No')
    expect(info[7].value).toBe('Sí — Lamborghini')
  })

  it('in-memory book: Report Info first, stamp, header, grid order, suffix and empty goal (R1, R2)', async () => {
    const labels = productionGoalExportLabels('en')
    const workbook = buildTableExportWorkbook({
      reportInfoSheet: labels.reportInfo,
      reportInfoHeader: { field: labels.field, value: labels.value },
      reportInfo: [{ field: 'Report', value: labels.reportName }],
      dataSheet: labels.reportName,
      stamp: 'Generated 10/27/2026 3:15 PM ET · Production vs Goal by Dealer',
      columns: productionGoalColumns(labels, new Set([2])),
      rows: sortLikeProductionGrid(rows),
    })
    const buffer = await workbook.xlsx.writeBuffer()
    const back = new ExcelJS.Workbook()
    await back.xlsx.load(buffer as ArrayBuffer)

    expect(back.worksheets.map((s) => s.name)).toEqual(['Report Info', 'Production vs Goal by Dealer'])
    const info = back.getWorksheet('Report Info')!
    expect(info.getRow(1).values).toEqual([undefined, 'Field', 'Value'])
    expect(info.getRow(2).values).toEqual([undefined, 'Report', 'Production vs Goal by Dealer'])

    const data = back.getWorksheet('Production vs Goal by Dealer')!
    expect(data.getCell('A1').value).toBe('Generated 10/27/2026 3:15 PM ET · Production vs Goal by Dealer')
    expect(data.getRow(2).values).toEqual([
      undefined,
      'Dealer',
      'WOs Done',
      'Production Value',
      'Goal',
      'Attainment %',
    ])
    expect(data.getRow(3).values).toEqual([undefined, 'Lexus PB', 20, 3000, 2500, 120])
    expect(data.getRow(4).values).toEqual([undefined, 'Toyota Miami', 10, 1000.5, 2000, 50])
    // Lamborghini: removed, no goal → Goal and Attainment % empty.
    expect(data.getRow(5).getCell(1).value).toBe('Lamborghini (removed)')
    expect(data.getRow(5).getCell(3).value).toBe(114996.53)
    expect(data.getRow(5).getCell(4).value).toBeNull()
    expect(data.getRow(5).getCell(5).value).toBeNull()
    expect(data.getRow(3).getCell(3).numFmt).toBe('#,##0.00')
  })
})
