import type ExcelJS from 'exceljs'

import { formatNyStamp, ymdToUs } from '../punch/punch-export-format'
import type { ReportInfoRow } from '../shared/export/report-info-sheet'
import {
  buildMultiSheetExportWorkbook,
  type TableExportColumn,
  type TableExportSheet,
} from '../shared/export/table-export-xlsx'
import type { ClosingPeriodDto, ClosingRowDto, ClosingScope, MonthlyClosingDto } from './dto/monthly-closing.dto'
import { type ByServiceRow, fromCents, groupByService } from './monthly-closing-math'
import { TINT_CLOSING_COLUMN_NOTES } from './tint-closing-column-notes'

/**
 * Excel del Monthly Closing y del Window Tint Closing (T5 de plans/plan-monthly-closing/PLAN.md, §5.3 de
 * plans/plan-reporte-tint/PLAN.md): Report Info, Summary, By service (solo tint), Income, Payroll y Expenses.
 * Textos de MC §5.4.6 y tint §5.4.
 */

const MONTHS = [
  'January',
  'February',
  'March',
  'April',
  'May',
  'June',
  'July',
  'August',
  'September',
  'October',
  'November',
  'December',
]

const REMOVED_SUFFIX = '(removed)'

export const CLOSING_REPORT_NAME: Record<ClosingScope, string> = {
  all: 'Monthly Closing',
  tint: 'Window Tint Closing',
}

/** «2026-09» → «September 2026» (título del detalle y Report Info). */
export function closingMonthLabel(month: string): string {
  const [y, m] = month.split('-')
  return `${MONTHS[Number(m) - 1] ?? m} ${y}`
}

/** «Monthly Closing 09-2026»: el resto del nombre lo pone buildNyStampedExportFilename con el sello de NY. */
export function closingExportPrefix(scope: ClosingScope, month: string): string {
  const [y, m] = month.split('-')
  return `${CLOSING_REPORT_NAME[scope]} ${m}-${y}`
}

/** «08/31/2026 – 09/15/2026», con «(calculated through …)» o «(not calculated yet)» (MC §5.4.5). */
export function closingPeriodLabel(p: ClosingPeriodDto): string {
  const range = `${ymdToUs(p.desde)} – ${ymdToUs(p.hasta)}`
  if (p.status === 'partial' && p.calculatedThrough) return `${range} (calculated through ${ymdToUs(p.calculatedThrough)})`
  if (p.status === 'notCalculated') return `${range} (not calculated yet)`
  return range
}

export interface ClosingWorkbookInput {
  scope: ClosingScope
  month: string
  generatedAt: Date
  generatedBy: string
  /** «All» o los nombres de los dealers del filtro. */
  dealersLabel: string
  includeRemovedDealers: boolean
  removedWithRows: readonly string[]
  periods: readonly ClosingPeriodDto[]
  summary: Omit<MonthlyClosingDto, 'scope' | 'month'>
  income: readonly {
    dealerId: number
    nro: string
    dateFrom: string
    dateTo: string
    department: string
    service: string
    qty: number
    cents: number
    /** Window Tint Closing: «tint» en el servicio; null en el Monthly Closing. */
    tint: boolean | null
    /** Window Tint Closing: fila en rojo (isNonTintWarning); null en el Monthly Closing. */
    warn: boolean | null
  }[]
  payroll: readonly {
    idDealer: number | null
    periodoDesde: string
    periodoHasta: string
    employee: string
    position: string
    cents: number
  }[]
  expenses: readonly {
    date: string
    dealerId: number
    dealer: string
    vendor: string
    category: string
    cents: number
    notes: string
  }[]
  dealerName: (id: number) => string
  isRemoved: (id: number) => boolean
}

export function buildClosingReportInfo(input: ClosingWorkbookInput): ReportInfoRow[] {
  const name = CLOSING_REPORT_NAME[input.scope]
  return [
    { field: 'Report', value: name },
    { field: 'Generated', value: formatNyStamp(input.generatedAt) },
    { field: 'Generated by', value: input.generatedBy },
    { field: 'Screen', value: `Reports › ${name}` },
    { field: 'Month', value: closingMonthLabel(input.month) },
    { field: 'Dealers', value: input.dealersLabel },
    {
      field: 'Include removed dealers',
      value: input.includeRemovedDealers
        ? input.removedWithRows.length
          ? `Yes — ${input.removedWithRows.join(', ')}`
          : 'Yes'
        : 'No',
    },
    { field: 'Pay periods', value: input.periods.map(closingPeriodLabel).join(', ') || '—' },
    ...(input.scope === 'tint'
      ? [
          {
            field: 'Tint services',
            value: 'All services of work orders assigned to tinters; services without «tint» in their name are marked',
          },
          { field: 'Tinters', value: 'Role name contains «tint» and Piecework payment type' },
          {
            field: 'Rows in red',
            value: 'Services without «tint» in their name and an amount other than $0, from work orders assigned to tinters',
          },
          { field: 'Expense category', value: 'Window Tint Film' },
        ]
      : []),
  ]
}

/** Columnas del Summary: MC con Accident; tint con Vehicles y la nota de cada columna (D5 del tint). */
export function closingSummaryColumns(
  scope: ClosingScope,
  isRemoved: (id: number) => boolean,
): TableExportColumn<ClosingRowDto>[] {
  const tint = scope === 'tint'
  const notes = tint ? TINT_CLOSING_COLUMN_NOTES : null
  const dealer: TableExportColumn<ClosingRowDto> = {
    header: 'Dealer',
    width: 40,
    kind: 'text',
    value: (r) => (r.dealerId > 0 && isRemoved(r.dealerId) ? `${r.dealer} ${REMOVED_SUFFIX}` : r.dealer),
    note: notes?.dealer,
  }
  const money = (header: string, key: 'income' | 'payroll' | 'expenses' | 'profit', note?: string) =>
    ({ header, width: 16, kind: 'money', value: (r) => r[key], note }) as TableExportColumn<ClosingRowDto>
  return [
    dealer,
    ...(tint
      ? [{ header: 'Vehicles', width: 12, kind: 'int', value: (r) => r.vehicles, note: notes?.vehicles } as TableExportColumn<ClosingRowDto>]
      : []),
    money('Income', 'income', notes?.income),
    money('Payroll', 'payroll', notes?.payroll),
    money('Expenses', 'expenses', notes?.expenses),
    money('Profit/Loss', 'profit', notes?.profit),
    { header: '%', width: 10, kind: 'pct', value: (r) => r.pct, note: notes?.pct },
    ...(tint
      ? []
      : [
          {
            header: 'Accident',
            width: 14,
            kind: 'money',
            value: (r) => (r.accident ? r.accident : null),
          } as TableExportColumn<ClosingRowDto>,
        ]),
  ]
}

export function buildClosingWorkbook(input: ClosingWorkbookInput): ExcelJS.Workbook {
  const name = CLOSING_REPORT_NAME[input.scope]
  const stamp = `Generated ${formatNyStamp(input.generatedAt)} · ${name}`
  const dealer = (id: number | null) => {
    const n = id == null || id === 0 ? 'Without dealer' : input.dealerName(id)
    return id && input.isRemoved(id) ? `${n} ${REMOVED_SUFFIX}` : n
  }
  const summaryRows: ClosingRowDto[] = [
    ...input.summary.rows,
    input.summary.total,
    ...(input.summary.withoutDealer ? [input.summary.withoutDealer] : []),
  ]
  const byDealerName = <T>(rows: readonly T[], id: (r: T) => number | null) =>
    [...rows].sort((a, b) => dealer(id(a)).localeCompare(dealer(id(b))))

  type Income = ClosingWorkbookInput['income'][number]
  type Payroll = ClosingWorkbookInput['payroll'][number]
  type Expense = ClosingWorkbookInput['expenses'][number]
  type ByService = ByServiceRow

  const sheets: TableExportSheet<unknown>[] = [
    {
      name: 'Summary',
      stamp,
      columns: closingSummaryColumns(input.scope, input.isRemoved),
      rows: summaryRows,
    } as TableExportSheet<ClosingRowDto> as TableExportSheet<unknown>,
  ]
  if (input.scope === 'tint') {
    const byService: TableExportSheet<ByService> = {
      name: 'By service',
      stamp,
      columns: [
        { header: 'Dealer', width: 40, kind: 'text', value: (r) => dealer(r.dealerId) },
        { header: 'Department', width: 24, kind: 'text', value: (r) => r.department },
        { header: 'Service', width: 40, kind: 'text', value: (r) => r.service },
        { header: 'Vehicles', width: 12, kind: 'int', value: (r) => r.vehicles, note: TINT_CLOSING_COLUMN_NOTES.vehicles },
        { header: 'Amount', width: 16, kind: 'money', value: (r) => fromCents(r.cents), note: TINT_CLOSING_COLUMN_NOTES.income },
      ],
      rows: byDealerName(groupByService(input.income), (r) => r.dealerId).sort(
        (a, b) =>
          dealer(a.dealerId).localeCompare(dealer(b.dealerId)) ||
          a.department.localeCompare(b.department) ||
          a.service.localeCompare(b.service),
      ),
      rowTone: (r) => (r.warn ? 'warn' : undefined),
    }
    sheets.push(byService as TableExportSheet<unknown>)
  }
  const income: TableExportSheet<Income> = {
    name: 'Income',
    stamp,
    columns: [
      { header: 'Dealer', width: 40, kind: 'text', value: (r) => dealer(r.dealerId) },
      { header: '#Invoice', width: 18, kind: 'text', value: (r) => r.nro },
      { header: 'Date From', width: 12, kind: 'text', value: (r) => ymdToUs(r.dateFrom) },
      { header: 'Date To', width: 12, kind: 'text', value: (r) => ymdToUs(r.dateTo) },
      { header: 'Department', width: 24, kind: 'text', value: (r) => r.department },
      { header: 'Service', width: 40, kind: 'text', value: (r) => r.service },
      ...(input.scope === 'tint'
        ? [{ header: 'Qty', width: 8, kind: 'int', value: (r) => r.qty } as TableExportColumn<Income>]
        : []),
      { header: 'Total', width: 14, kind: 'money', value: (r) => fromCents(r.cents) },
    ],
    rows: byDealerName(input.income, (r) => r.dealerId),
    ...(input.scope === 'tint' ? { rowTone: (r: Income) => (r.warn ? ('warn' as const) : undefined) } : {}),
  }
  const payroll: TableExportSheet<Payroll> = {
    name: 'Payroll',
    stamp,
    columns: [
      {
        header: 'Pay period',
        width: 26,
        kind: 'text',
        value: (r) => `${ymdToUs(r.periodoDesde)} – ${ymdToUs(r.periodoHasta)}`,
      },
      { header: 'Dealer', width: 40, kind: 'text', value: (r) => dealer(r.idDealer) },
      { header: 'Employee', width: 36, kind: 'text', value: (r) => r.employee },
      { header: 'Position', width: 22, kind: 'text', value: (r) => r.position },
      { header: 'Amount', width: 14, kind: 'money', value: (r) => fromCents(r.cents) },
    ],
    rows: byDealerName(input.payroll, (r) => r.idDealer),
  }
  const expenses: TableExportSheet<Expense> = {
    name: 'Expenses',
    stamp,
    columns: [
      { header: 'Date', width: 12, kind: 'text', value: (r) => ymdToUs(r.date) },
      { header: 'Dealer', width: 40, kind: 'text', value: (r) => dealer(r.dealerId) },
      { header: 'Vendor', width: 30, kind: 'text', value: (r) => r.vendor },
      { header: 'Category', width: 24, kind: 'text', value: (r) => r.category },
      { header: 'Amount', width: 14, kind: 'money', value: (r) => fromCents(r.cents) },
      { header: 'Notes', width: 50, kind: 'text', value: (r) => r.notes },
    ],
    rows: byDealerName(input.expenses, (r) => r.dealerId),
  }
  sheets.push(
    income as TableExportSheet<unknown>,
    payroll as TableExportSheet<unknown>,
    expenses as TableExportSheet<unknown>,
  )

  return buildMultiSheetExportWorkbook({
    reportInfoSheet: 'Report Info',
    reportInfoHeader: { field: 'Field', value: 'Value' },
    reportInfo: buildClosingReportInfo(input),
    sheets,
  })
}
